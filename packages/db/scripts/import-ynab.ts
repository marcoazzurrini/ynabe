/**
 * Turns a YNAB export into imports/ynab.sql, which replaces the whole
 * budget. Unzip the export into imports/ynab, run
 * `bun run --cwd packages/db import:ynab`, then load the result with
 * `bun run --cwd apps/web db:import ynab.sql`. Another folder can be given as an
 * absolute path.
 */

import { readdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { planMonth } from "@ynabe/budget";
import { readYnab } from "@ynabe/import";

const text = (value: string | null) =>
  value === null ? "NULL" : `'${value.replaceAll("'", "''")}'`;

const folder =
  Bun.argv[2] ??
  fileURLToPath(new URL("../../../imports/ynab", import.meta.url));

const files = await readdir(folder);

const read = (ending: string) => {
  const name = files.find((file) => file.endsWith(ending));

  if (!name) {
    throw new Error(`No file ending in "${ending}" in ${folder}`);
  }

  return Bun.file(path.join(folder, name)).text();
};

const budget = readYnab(await read("Register.csv"), await read("Plan.csv"));

const lines = [
  "-- Generated by scripts/import-ynab.ts. Replaces the whole budget.",
  "DELETE FROM transactions;",
  "DELETE FROM assignments;",
  "DELETE FROM categories;",
  "DELETE FROM category_groups;",
  "DELETE FROM accounts;",
  ...budget.accounts.map(
    ({ id, name }) =>
      `INSERT INTO accounts (id, name) VALUES (${text(id)}, ${text(name)});`
  ),
  ...budget.groups.map(
    ({ id, name, position }) =>
      `INSERT INTO category_groups (id, name, position) VALUES (${text(id)}, ${text(name)}, ${position});`
  ),
  ...budget.categories.map(
    ({ groupId, id, name, position }) =>
      `INSERT INTO categories (id, group_id, name, position) VALUES (${text(id)}, ${text(groupId)}, ${text(name)}, ${position});`
  ),
  ...budget.assignments.map(
    ({ amount, categoryId, month }) =>
      `INSERT INTO assignments (category_id, month, amount) VALUES (${text(categoryId)}, ${text(month)}, ${amount});`
  ),
  ...budget.transactions.map(
    (row) =>
      `INSERT INTO transactions (id, account_id, date, payee, memo, amount, category_id, cleared, transfer_account_id) VALUES (${[
        text(row.id),
        text(row.accountId),
        text(row.date),
        text(row.payee),
        text(row.memo),
        row.amount,
        text(row.categoryId),
        text(row.cleared),
        text(row.transferAccountId),
      ].join(", ")});`
  ),
];

const output = new URL("../../../imports/ynab.sql", import.meta.url);

await Bun.write(output, `${lines.join("\n")}\n`);

// Check the engine against the balances YNAB showed, month by month.
const data = {
  ...budget,
  transactions: budget.transactions.map((row) => ({
    ...row,
    transfer: row.transferAccountId !== null,
  })),
};

const months = [...new Set(budget.balances.map(({ month }) => month))];
const differing = new Set<string>();

for (const month of months) {
  const plan = planMonth(data, month);

  for (const balance of budget.balances) {
    const category = plan.categories.find(
      ({ id }) => id === balance.categoryId
    );

    if (balance.month === month && category?.available !== balance.available) {
      differing.add(month);
    }
  }
}

const dates = budget.transactions.map(({ date }) => date).toSorted();

// Counts only: the terminal should not show private rows.
console.log(
  [
    `Accounts: ${budget.accounts.length}`,
    `Groups: ${budget.groups.length}`,
    `Categories: ${budget.categories.length}`,
    `Assignments: ${budget.assignments.length}`,
    `Transactions: ${budget.transactions.length} (${dates[0]} to ${dates.at(-1)})`,
    differing.size === 0
      ? `Balances match YNAB in all ${months.length} months.`
      : `Balances differ from YNAB in ${differing.size} of ${months.length} months, first in ${[...differing].toSorted()[0]}.`,
    `Wrote ${path.relative(process.cwd(), output.pathname)}`,
  ].join("\n")
);
